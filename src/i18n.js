let _locale = 'en';

export function setLocale(code) {
  if (TRANSLATIONS[code]) {
    _locale = code;
  }
}

export function getLocale() {
  return _locale;
}

export function t(key, fallback) {
  return TRANSLATIONS[_locale]?.[key] ?? TRANSLATIONS['en']?.[key] ?? fallback ?? key;
}
